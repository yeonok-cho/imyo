# 3. 기본 통계 함수
# ============================================================

def z_normalize(x: np.ndarray, eps: float = 1e-8) -> np.ndarray:
    """프로파일 단위 Z-normalization."""
    x = np.asarray(x, dtype=np.float64)
    return (x - np.mean(x)) / max(np.std(x), eps)


def linear_detrend(x: np.ndarray) -> np.ndarray:
    """1차 선형 추세 제거."""
    x = np.asarray(x, dtype=np.float64)

    t = np.linspace(-1.0, 1.0, len(x))
    design = np.column_stack([np.ones(len(x)), t])

    beta, *_ = np.linalg.lstsq(design, x, rcond=None)
    trend = design @ beta

    return x - trend


def lag1_autocorrelation(x: np.ndarray) -> float:
    """Lag-1 autocorrelation."""
    x = np.asarray(x, dtype=np.float64)

    if len(x) < 2:
        return np.nan

    x1 = x[:-1]
    x2 = x[1:]

    if np.std(x1) < 1e-12 or np.std(x2) < 1e-12:
        return 0.0

    return float(np.corrcoef(x1, x2)[0, 1])


def normalized_shape(x: np.ndarray) -> np.ndarray:
    """실제 통계 계산 방식과 동일한 detrend + Z-normalization."""
    return z_normalize(linear_detrend(x))


