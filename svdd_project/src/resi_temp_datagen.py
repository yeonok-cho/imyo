def tune_noise_scale(
    base_shape: np.ndarray,
    noise_shape: np.ndarray,
    target_lag1: float,
    max_scale: float = 10.0,
    iterations: int = 35,
) -> float:
    """
    base_shape + scale * noise_shape의 lag-1 값이
    target_lag1에 가까워지도록 noise scale 탐색.
    """
    low = 0.0
    high = max_scale

    base_lag = lag1_autocorrelation(normalized_shape(base_shape))

    # 이미 목표보다 자기상관이 낮으면 noise를 추가하지 않음.
    if base_lag <= target_lag1:
        return 0.0

    best_scale = 0.0
    best_error = abs(base_lag - target_lag1)

    for _ in range(iterations):
        mid = (low + high) / 2.0

        candidate = normalized_shape(
            base_shape + mid * noise_shape
        )

        current_lag = lag1_autocorrelation(candidate)
        error = abs(current_lag - target_lag1)

        if error < best_error:
            best_error = error
            best_scale = mid

        # Noise 증가 → 일반적으로 lag-1 감소
        if current_lag > target_lag1:
            low = mid
        else:
            high = mid

    return best_scale


# ============================================================
# 8. Profile 표준편차 분포 설정
# ============================================================

def calculate_profile_std_distribution(
    config: SignalConfig,
) -> tuple[float, float]:
    """
    전체 분산 ≈ profile mean 간 분산 + profile 내부 분산을 이용하여
    profile std 분포의 RMS를 추정.

    E[S²] = global_std² - profile_mean_std²
    Var(S) = E[S²] - E[S]²
    """
    expected_squared_std = max(
        config.global_std**2 - config.profile_mean_std**2,
        config.profile_std_mean**2,
    )

    profile_std_variance = max(
        expected_squared_std - config.profile_std_mean**2,
        1e-8,
    )

    return (
        config.profile_std_mean,
        np.sqrt(profile_std_variance),
    )


def sample_positive_profile_std(
    config: SignalConfig,
    rng: np.random.Generator,
) -> float:
    """
    양수 값만 가지도록 log-normal 분포로 profile std 생성.
    """
    mean_std, std_of_std = calculate_profile_std_distribution(config)

    variance = std_of_std**2

    sigma2 = np.log(
        1.0 + variance / max(mean_std**2, 1e-12)
    )
    sigma = np.sqrt(sigma2)

    mu = np.log(mean_std) - sigma2 / 2.0

    value = rng.lognormal(mean=mu, sigma=sigma)

    # 과도하게 큰 scale 방지
    upper_limit = mean_std + 4.0 * std_of_std
    return float(np.clip(value, mean_std * 0.15, upper_limit))


# ============================================================
# 9. 정상 Shape 생성
# ============================================================

def generate_normalized_profile_shape(
    config: SignalConfig,
    rng: np.random.Generator,
) -> tuple[np.ndarray, float]:
    """
    평균 shape와 std shape를 바탕으로 normalized profile 한 개 생성.
    """
    mean_shape = np.asarray(config.mean_shape, dtype=np.float64)
    std_shape = np.asarray(config.std_shape, dtype=np.float64)

    if len(mean_shape) != len(std_shape):
        raise ValueError(
            f"{config.name}: mean_shape와 std_shape 길이가 다릅니다."
        )

    if len(mean_shape) == 0:
        raise ValueError(
            f"{config.name}: shape 배열이 비어 있습니다."
        )

    n = len(mean_shape)

    # 1. 평균 shape 시간축 변형
    warp_strength = abs(
        rng.normal(0.0, config.time_warp_std)
    )

    warped_mean = time_warp_shape(
        mean_shape,
        warp_strength=warp_strength,
        rng=rng,
    )

    # 2. 프로파일별 amplitude와 offset 변동
    amplitude = rng.normal(
        loc=1.0,
        scale=config.amplitude_jitter_std,
    )

    offset = rng.normal(
        loc=0.0,
        scale=config.offset_jitter_std,
    )

    base_shape = amplitude * warped_mean + offset

    # 3. 프로파일의 목표 lag-1 설정
    target_lag1 = sample_target_lag1(config, rng)

    # 4. Noise 자체도 어느 정도 temporal correlation을 갖도록 생성
    noise_phi = np.clip(
        target_lag1 - rng.uniform(0.05, 0.25),
        -0.20,
        0.98,
    )

    ar_noise = generate_ar1_noise(
        length=n,
        phi=noise_phi,
        rng=rng,
    )

    # 저주파 profile variation
    low_frequency_noise = smooth_noise(
        length=n,
        rng=rng,
        window=max(15, n // 12),
    )

    combined_noise = (
        0.75 * ar_noise
        + 0.25 * low_frequency_noise
    )

    combined_noise = z_normalize(combined_noise)

    # 위치별 변동성 반영
    pointwise_noise = combined_noise * std_shape

    # 5. 목표 lag-1과 비슷해지도록 noise 크기 조정
    noise_scale = tune_noise_scale(
        base_shape=base_shape,
        noise_shape=pointwise_noise,
        target_lag1=target_lag1,
    )

    generated_shape = base_shape + noise_scale * pointwise_noise

    # 6. 통계 정의에 맞춰 detrend + Z-normalization
    generated_shape = normalized_shape(generated_shape)

    return generated_shape, target_lag1


# ============================================================
# 10. Raw Profile 변환
# ============================================================

def convert_shape_to_raw(
    shape: np.ndarray,
    config: SignalConfig,
    rng: np.random.Generator,
    enforce_range: bool = True,
) -> tuple[np.ndarray, float, float]:
    """
    Normalized shape를 실제 raw scale로 변환.
    """
    profile_mean = rng.normal(
        loc=config.profile_mean_mean,
        scale=config.profile_mean_std,
    )

    profile_std = sample_positive_profile_std(
        config=config,
        rng=rng,
    )

    raw_profile = profile_mean + profile_std * z_normalize(shape)

    if enforce_range:
        raw_profile = np.clip(
            raw_profile,
            config.raw_min,
            config.raw_max,
        )

    return raw_profile, profile_mean, profile_std


# ============================================================
# 11. 선택적 이상 패턴 생성
# ============================================================

def inject_anomaly(
    profile: np.ndarray,
    anomaly_type: str,
    strength: float,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    가상 이상 패턴 삽입.

    anomaly_type:
      - spike
      - level_shift
      - drift
      - local_drop
      - local_rise
      - oscillation
      - timing_shift
      - variance_increase
    """
    x = np.asarray(profile, dtype=np.float64).copy()
    n = len(x)

    signal_scale = max(np.std(x), 1e-8)

    if anomaly_type == "spike":
        center = rng.integers(int(n * 0.1), int(n * 0.9))
        width = rng.integers(1, max(2, n // 50))

        start = max(0, center - width)
        end = min(n, center + width + 1)

        x[start:end] += (
            strength
            * signal_scale
            * rng.choice([-1.0, 1.0])
        )

    elif anomaly_type == "level_shift":
        start = rng.integers(int(n * 0.2), int(n * 0.8))

        x[start:] += (
            strength
            * signal_scale
            * rng.choice([-1.0, 1.0])
        )

    elif anomaly_type == "drift":
        direction = rng.choice([-1.0, 1.0])

        x += direction * strength * signal_scale * np.linspace(
            0.0,
            1.0,
            n,
        )

    elif anomaly_type in {"local_drop", "local_rise"}:
        center = rng.integers(int(n * 0.2), int(n * 0.8))
        width = rng.uniform(n * 0.02, n * 0.10)

        t = np.arange(n)
        bump = np.exp(
            -0.5 * ((t - center) / width) ** 2
        )

        direction = -1.0 if anomaly_type == "local_drop" else 1.0

        x += direction * strength * signal_scale * bump

    elif anomaly_type == "oscillation":
        start = rng.integers(int(n * 0.1), int(n * 0.6))
        end = rng.integers(
            max(start + 10, int(n * 0.5)),
            n,
        )

        length = end - start
        cycles = rng.uniform(3.0, 12.0)

        oscillation = np.sin(
            np.linspace(0.0, 2.0 * np.pi * cycles, length)
        )

        x[start:end] += (
            strength * signal_scale * oscillation
        )

    elif anomaly_type == "timing_shift":
        shift = int(
            np.clip(
                strength * n * rng.choice([-1.0, 1.0]),
                -n // 5,
                n // 5,
            )
        )

        x = np.roll(x, shift)

        # np.roll의 경계 불연속 완화
        if shift > 0:
            x[:shift] = x[shift]
        elif shift < 0:
            x[shift:] = x[shift - 1]

    elif anomaly_type == "variance_increase":
        start = rng.integers(int(n * 0.2), int(n * 0.7))

        additional_noise = rng.normal(
            loc=0.0,
            scale=strength * signal_scale,
            size=n - start,
        )

        x[start:] += additional_noise

    else:
        raise ValueError(
            f"지원하지 않는 anomaly_type입니다: {anomaly_type}"
        )

    return x


ANOMALY_TYPES = [
    "spike",
    "level_shift",
    "drift",
    "local_drop",
    "local_rise",
    "oscillation",
    "timing_shift",
    "variance_increase",
]


# ============================================================
# 12. 전체 Dataset 생성
# ============================================================

def generate_signal_dataset(
    config: SignalConfig,
    n_profiles: int,
    anomaly_ratio: float = 0.0,
    anomaly_types: Optional[list[str]] = None,
    enforce_range: bool = True,
    random_state: Optional[int] = None,
) -> tuple[np.ndarray, pd.DataFrame]:
    """
    특정 signal의 가상 dataset 생성.

    Returns
    -------
    profiles:
        shape = (n_profiles, 300)

    metadata:
        프로파일별 생성 통계와 이상 여부
    """
    if not 0.0 <= anomaly_ratio <= 1.0:
        raise ValueError("anomaly_ratio는 0과 1 사이여야 합니다.")

    rng = np.random.default_rng(random_state)

    if anomaly_types is None:
        anomaly_types = ANOMALY_TYPES

    profiles = []
    metadata = []

    for profile_id in range(n_profiles):
        # Normalized shape 생성
        shape, target_lag1 = generate_normalized_profile_shape(
            config=config,
            rng=rng,
        )

        # Raw scale 변환
        raw_profile, sampled_mean, sampled_std = convert_shape_to_raw(
            shape=shape,
            config=config,
            rng=rng,
            enforce_range=False,
        )

        is_anomaly = rng.random() < anomaly_ratio
        anomaly_type = None
        anomaly_strength = 0.0

        if is_anomaly:
            anomaly_type = str(rng.choice(anomaly_types))
            anomaly_strength = float(
                rng.uniform(0.5, 2.0)
            )

            raw_profile = inject_anomaly(
                profile=raw_profile,
                anomaly_type=anomaly_type,
                strength=anomaly_strength,
                rng=rng,
            )

        if enforce_range:
            raw_profile = np.clip(
                raw_profile,
                config.raw_min,
                config.raw_max,
            )

        normalized = normalized_shape(raw_profile)

        profiles.append(raw_profile)

        metadata.append({
            "signal": config.name,
            "profile_id": profile_id,
            "is_anomaly": int(is_anomaly),
            "anomaly_type": anomaly_type,
            "anomaly_strength": anomaly_strength,
            "sampled_profile_mean": sampled_mean,
            "sampled_profile_std": sampled_std,
            "actual_profile_mean": float(np.mean(raw_profile)),
            "actual_profile_std": float(np.std(raw_profile)),
            "actual_min": float(np.min(raw_profile)),
            "actual_max": float(np.max(raw_profile)),
            "target_lag1": target_lag1,
            "actual_lag1": lag1_autocorrelation(normalized),
        })

    return (
        np.asarray(profiles, dtype=np.float64),
        pd.DataFrame(metadata),
    )


# ============================================================
# 13. RESI와 TEMP Pair Dataset 생성
# ============================================================

def generate_paired_dataset(
    n_profiles: int,
    anomaly_ratio: float = 0.0,
    random_state: int = 42,
) -> tuple[np.ndarray, np.ndarray, pd.DataFrame]:
    """
    동일한 profile_id 기준으로 RESI와 TEMP 생성.

    현재는 RESI-TEMP 교차상관 정보가 없으므로 두 신호의
    shape variation은 독립적으로 생성함.
    """
    resi_profiles, resi_metadata = generate_signal_dataset(
        config=RESI_CONFIG,
        n_profiles=n_profiles,
        anomaly_ratio=anomaly_ratio,
        random_state=random_state,
    )

    temp_profiles, temp_metadata = generate_signal_dataset(
        config=TEMP_CONFIG,
        n_profiles=n_profiles,
        anomaly_ratio=anomaly_ratio,
        random_state=random_state + 1,
    )

    resi_metadata = resi_metadata.add_prefix("resi_")
    temp_metadata = temp_metadata.add_prefix("temp_")

    metadata = pd.concat(
        [resi_metadata, temp_metadata],
        axis=1,
    )

    return resi_profiles, temp_profiles, metadata


# ============================================================
# 14. 생성 데이터 검증
# ============================================================

def summarize_generated_data(
    profiles: np.ndarray,
    name: str,
) -> pd.Series:
    """생성 데이터의 주요 통계 출력."""
    normalized_profiles = np.asarray([
        normalized_shape(profile)
        for profile in profiles
    ])

    lag1_values = np.asarray([
        lag1_autocorrelation(profile)
        for profile in normalized_profiles
    ])

    profile_means = np.mean(profiles, axis=1)
    profile_stds = np.std(profiles, axis=1)

    flattened = profiles.reshape(-1)

    return pd.Series({
        "signal": name,
        "n_profiles": len(profiles),
        "n_points": profiles.shape[1],
        "global_mean": np.mean(flattened),
        "global_std": np.std(flattened),
        "global_min": np.min(flattened),
        "global_max": np.max(flattened),
        "mean_of_profile_means": np.mean(profile_means),
        "std_of_profile_means": np.std(profile_means),
        "mean_of_profile_stds": np.mean(profile_stds),
        "normalized_global_mean": np.mean(normalized_profiles),
        "normalized_global_std": np.std(normalized_profiles),
        "normalized_iqr": (
            np.percentile(normalized_profiles, 75)
            - np.percentile(normalized_profiles, 25)
        ),
        "mean_lag1": np.mean(lag1_values),
        "median_lag1": np.median(lag1_values),
    })


