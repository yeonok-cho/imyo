# 4. AR(1) 및 Smooth Noise 생성
# ============================================================

def generate_ar1_noise(
    length: int,
    phi: float,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    분산이 약 1이 되도록 정규화된 AR(1) noise 생성.
    phi가 클수록 연속된 값이 부드럽게 연결됨.
    """
    phi = float(np.clip(phi, -0.99, 0.9995))

    innovation_std = np.sqrt(max(1.0 - phi**2, 1e-8))
    noise = np.zeros(length, dtype=np.float64)

    noise[0] = rng.normal()

    for i in range(1, length):
        noise[i] = (
            phi * noise[i - 1]
            + innovation_std * rng.normal()
        )

    return z_normalize(noise)


def smooth_noise(
    length: int,
    rng: np.random.Generator,
    window: int,
) -> np.ndarray:
    """저주파 형태 변화를 위한 이동평균 기반 smooth noise."""
    noise = rng.normal(size=length)

    window = max(3, int(window))
    if window % 2 == 0:
        window += 1

    kernel = np.ones(window, dtype=np.float64) / window
    smoothed = np.convolve(noise, kernel, mode="same")

    return z_normalize(smoothed)


# ============================================================
# 5. Time Warping
# ============================================================

def time_warp_shape(
    shape: np.ndarray,
    warp_strength: float,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    프로파일의 전체 진행 속도와 국부적인 시간축 변동을 생성.
    값 자체가 아니라 shape timing만 변형.
    """
    n = len(shape)

    original_t = np.linspace(0.0, 1.0, n)

    warp_noise = smooth_noise(
        length=n,
        rng=rng,
        window=max(11, n // 15),
    )

    warped_increment = 1.0 + warp_strength * warp_noise
    warped_increment = np.clip(warped_increment, 0.05, None)

    warped_t = np.cumsum(warped_increment)
    warped_t -= warped_t[0]
    warped_t /= warped_t[-1]

    return np.interp(original_t, warped_t, shape)


