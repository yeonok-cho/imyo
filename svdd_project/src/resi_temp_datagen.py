# 6. 목표 Lag-1 분포 생성
# ============================================================

def sample_target_lag1(
    config: SignalConfig,
    rng: np.random.Generator,
) -> float:
    """
    Mean과 median이 다른 자기상관 분포를 간단한 mixture로 근사.

    RESI:
      대부분 높은 자기상관을 가지지만 일부 profile이 낮은 자기상관을 가짐.

    TEMP:
      대부분 매우 smooth하며 드물게 상대적으로 낮은 자기상관을 가짐.
    """
    mean_value = config.target_lag1_mean
    median_value = config.target_lag1_median

    if config.name == "ACT.RESI":
        high_probability = 0.80
        high_center = median_value
        high_std = 0.025

    else:
        high_probability = 0.90
        high_center = median_value
        high_std = 0.002

    low_center = (
        mean_value - high_probability * high_center
    ) / (1.0 - high_probability)

    if rng.random() < high_probability:
        target = rng.normal(high_center, high_std)
    else:
        low_std = 0.12 if config.name == "ACT.RESI" else 0.05
        target = rng.normal(low_center, low_std)

    return float(np.clip(target, -0.20, 0.9995))


